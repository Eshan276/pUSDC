// Generates src/abi.ts from the Foundry build output (run `forge build` in the repo root first).
import { readFileSync, writeFileSync } from "node:fs";
const art = (p) => JSON.parse(readFileSync(new URL(`../../out/${p}`, import.meta.url))).abi;
const pusdc = art("ProtectedWrapper.sol/ProtectedWrapper.json");
const erc20 = art("MockERC20.sol/MockERC20.json");
const scheduler = art("ScheduledSwap.sol/ScheduledSwap.json");
writeFileSync(
  new URL("../src/abi.ts", import.meta.url),
  `// Generated by scripts/gen-abi.mjs from the Foundry build. Do not edit.\n` +
    `export const pusdcAbi = ${JSON.stringify(pusdc, null, 2)} as const;\n\n` +
    `/** Plain ERC-20 plus the demo token's open \`mint\`. */\n` +
    `export const usdcAbi = ${JSON.stringify(erc20, null, 2)} as const;\n\n` +
    `/** Uniswap v4 scheduled swaps for protected accounts. */\n` +
    `export const schedulerAbi = ${JSON.stringify(scheduler, null, 2)} as const;\n`,
);
console.log(`wrote src/abi.ts (${pusdc.length} + ${erc20.length} entries)`);
